    function has(k) { return Object.prototype.hasOwnProperty.call(T, k); }
    function norm(s) { return s.replace(/\s+/g, " ").trim(); }

    function translateNode(node) {
      var p = node.parentNode;
      if (!p) { return; }
      var tag = p.nodeName;
      if (tag === "SCRIPT" || tag === "STYLE" || tag === "NOSCRIPT" || tag === "TEXTAREA") { return; }
      if (p.closest && p.closest(".hb-lang")) { return; }
      var raw = node.nodeValue;
      var key = norm(raw);
      if (!key || !has(key)) { return; }
      var lead = raw.match(/^\s*/)[0];
      var trail = raw.match(/\s*$/)[0];
      touched.push({ node: node, orig: raw });
      node.nodeValue = lead + T[key] + trail;
    }

    function walk(el) {
      if (el.nodeType === 3) { translateNode(el); return; }
      if (el.nodeType !== 1) { return; }
      var w = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, null, false);
      var list = [];
      while (w.nextNode()) { list.push(w.currentNode); }
      list.forEach(translateNode);
    }

    function translatePlaceholders() {
      var els = document.querySelectorAll("[placeholder]");
      Array.prototype.forEach.call(els, function (el) {
        var ph = el.getAttribute("placeholder");
        if (ph && has(ph)) {
          phTouched.push({ el: el, orig: ph });
          el.setAttribute("placeholder", T[ph]);
        }
      });
    }

    function restore() {
      touched.forEach(function (t) { if (t.node.parentNode) { t.node.nodeValue = t.orig; } });
      touched = [];
      phTouched.forEach(function (t) { t.el.setAttribute("placeholder", t.orig); });
      phTouched = [];
    }

    function startObserver() {
      if (observer || !("MutationObserver" in window)) { return; }
      observer = new MutationObserver(function (muts) {
        muts.forEach(function (m) {
          Array.prototype.forEach.call(m.addedNodes, function (n) { walk(n); });
        });
      });
      observer.observe(document.body, { childList: true, subtree: true });
    }

    function stopObserver() {
      if (observer) { observer.disconnect(); observer = null; }
    }

